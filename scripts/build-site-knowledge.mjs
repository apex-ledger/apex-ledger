// Turns the public website into the knowledge the site chat answers from.
//
//   node scripts/build-site-knowledge.mjs      -> src/server/siteKnowledge.generated.ts
//
// Every page under website/ except the agreement, the 404 page and the terms is reduced to its
// visible text (no scripts, styles or icons) so the assistant answers from exactly what a visitor
// can read on apexledger.ca and nothing else. Runs as part of `npm run build:web`.
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const site = path.join(root, 'website');
const SKIP = new Set(['404.html', 'agreement.html', 'terms.html']);
const MAX_PER_PAGE = 40000;

function textOf(html) {
  let s = html
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<svg[\s\S]*?<\/svg>/gi, ' ')
    .replace(/<dialog[\s\S]*?<\/dialog>/gi, ' ')
    .replace(/<(h[1-6]|p|li|tr|details|summary|article|section|div|br|th|td)[^>]*>/gi, '\n')
    .replace(/<[^>]+>/g, ' ');
  s = s.replace(/&#x27;/g, "'").replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&nbsp;/g, ' ').replace(/&middot;|·/g, '·');
  return s.split('\n').map((l) => l.replace(/\s+/g, ' ').trim()).filter(Boolean).join('\n');
}

const pages = fs.readdirSync(site).filter((f) => f.endsWith('.html') && !SKIP.has(f)).sort();
const parts = [];
for (const f of pages) {
  const html = fs.readFileSync(path.join(site, f), 'utf8');
  const title = (html.match(/<title>([^<]*)<\/title>/i)?.[1] ?? f).replace(/\s*\|\s*ApexLedger\s*$/, '').trim();
  const url = 'https://apexledger.ca/' + (f === 'index.html' ? '' : f);
  const body = textOf(html).slice(0, MAX_PER_PAGE);
  parts.push(`### ${title}\nURL: ${url}\n${body}`);
}
const knowledge = parts.join('\n\n');
const out = `// Generated by scripts/build-site-knowledge.mjs from website/*.html. Do not edit by hand.\nexport const SITE_KNOWLEDGE = ${JSON.stringify(knowledge)};\nexport const SITE_KNOWLEDGE_BUILT = ${JSON.stringify(new Date().toISOString().slice(0, 10))};\n`;
fs.writeFileSync(path.join(root, 'src', 'server', 'siteKnowledge.generated.ts'), out);
console.log(`site knowledge: ${pages.length} pages, ${knowledge.length} characters`);
